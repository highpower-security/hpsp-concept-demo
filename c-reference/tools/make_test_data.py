"""Turn the specification's examples and vectors into C test data.
Every example message in the spec (JSON notation) is converted to CBOR using the
spec's rule: members ending in _hex or _b64 become byte strings."""
import base64, json, os, sys
import cbor2
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
V = json.load(open(os.path.join(root, 'vectors/spec_vectors.json')))
EX = json.load(open(os.path.join(root, 'vectors/spec_examples.json')))

def b64(s):
    return base64.urlsafe_b64decode(s + '=' * (-len(s) % 4))
def conv(o):
    if isinstance(o, dict):
        r = {}
        for k, v in o.items():
            if k.endswith('_hex') and isinstance(v, str): v = bytes.fromhex(v)
            elif k.endswith('_b64') and isinstance(v, str): v = b64(v)
            elif k.endswith('_b64') and isinstance(v, list): v = [b64(i) for i in v]
            elif k.endswith('_hex') and isinstance(v, list): v = [bytes.fromhex(i) for i in v]
            else: v = conv(v)
            r[k] = v
        return r
    if isinstance(o, list): return [conv(x) for x in o]
    return o

msgs, skipped = [], []
for e in EX:
    try: o = json.loads(e if isinstance(e, str) else json.dumps(e))
    except Exception: continue
    if not isinstance(o, dict) or 'type' not in o: continue
    try: msgs.append((o.get('op'), o['type'], cbor2.dumps(conv(o), canonical=True)))
    except Exception as x: skipped.append((o.get('op'), str(x)))

def carr(name, b): return 'static const uint8_t %s[%d] = {%s};\n' % (name, len(b), ','.join('0x%02x' % c for c in b))
out = ['/* Generated by tools/make_test_data.py from the specification. Do not edit. */\n#include <stdint.h>\n#include <stddef.h>\n']
for k in ['uuidHex', 'nonceHex', 'signerHex', 'sigHex', 'inputHex', 'inputSha256']:
    out.append(carr('V_' + k.replace('Hex', '').upper(), bytes.fromhex(V[k])))
out.append(carr('V_PUB', bytes.fromhex(V['pubHex'])[1:]))
out.append('#define V_DEVICE_ID "%s"\n#define V_COUNTER %du\n#define V_CID %d\n#define V_DURATION %du\n#define V_EXPIRES %dull\n' % (
    V['deviceId'], V['grant']['counter'], V['grant']['cid'], V['grant']['duration_ms'], V['grant']['expires']))
seen = set(); blob = b''; n = 0; names = []
for op, t, b in msgs:
    if b in seen: continue
    seen.add(b); blob += len(b).to_bytes(2, 'big') + b; n += 1
    names.append('"%s:%s"' % (t, op or ''))
out.append(carr('EXAMPLES', blob))
out.append('#define N_EXAMPLES %d\nstatic const char *EXAMPLE_NAMES[] = {%s};\n' % (n, ','.join(names)))
def find(op, t):
    for o, ty, b in msgs:
        if o == op and ty == t: return b
for (op, t, nm) in [('hello', 'rsp', 'EX_HELLO_RSP'), ('unlock', 'cmd', 'EX_UNLOCK')]:
    out.append(carr(nm, find(op, t)))
open(os.path.join(root, 'tests/spec_data.h'), 'w').write(''.join(out))
keys = ['/* Generated by tools/make_test_data.py. TEST KEY ONLY: published, no security value. */\n#include <stdint.h>\n']
keys.append(carr('K_UUID', bytes.fromhex(V['uuidHex'])))
keys.append(carr('K_SIGNER', bytes.fromhex(V['signerHex'])))
keys.append(carr('K_PUB', bytes.fromhex(V['pubHex'])[1:]))
keys.append('#define K_DEVICE_ID "%s"\n' % V['deviceId'])
open(os.path.join(root, 'posix/test_keys.h'), 'w').write(''.join(keys))
print('examples:', n, 'skipped:', skipped)
